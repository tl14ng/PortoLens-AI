type RiskRating = Asset['riskRating'];

function buildHistory(return1Y: number): number[] {
  const start = 100;
  const end = Math.max(40, 100 + return1Y * 0.65);
  return Array.from({ length: 12 }, (_, i) => {
    const t = i / 11;
    const wave = Math.sin(i * 1.1) * 1.8;
    return Number((start + (end - start) * t + wave).toFixed(1));
  });
}

function makeIdx(
  ticker: string,
  name: string,
  sector: string,
  price: number,
  change1D: number,
  return1Y: number,
  beta: number,
  dividendYield: number,
  peRatio: number,
  marketCap: string,
  riskRating: RiskRating,
  description: string
): Asset {
  return {
    ticker,
    name,
    type: 'IDX_STOCK',
    sector,
    currency: 'IDR',
    price,
    change1D,
    return1Y,
    return3Y: Number((return1Y * 1.2).toFixed(1)),
    beta,
    dividendYield,
    peRatio,
    marketCap,
    riskRating,
    history12M: buildHistory(return1Y),
    description,
  };
}

